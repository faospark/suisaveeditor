/// Resolve an inventory slot's human-readable name & category from `(item_no, use_cnt)`.
pub fn resolve_inventory_item(item_no: i64, use_cnt: i64) -> (&'static str, String) {
    if item_no == 0 {
        return ("Empty", "—".to_string());
    }
    match use_cnt {
        0..=9 => ("Item", regular_item_name(item_no).to_string()),
        16 => ("Equip", equipment_name(item_no).to_string()),
        32 => ("Rune", rune_name(item_no).to_string()),
        48 => ("Farm", farming_item_name(item_no).to_string()),
        64 => ("Trade", trade_item_name(item_no).to_string()),
        80 => ("Base", base_item_name(item_no).to_string()),
        c if c >= 96 => {
            let name = food_item_name(item_no);
            if name == "Unknown Food Dish" {
                ("Food", format!("Food Dish #{}", item_no))
            } else {
                ("Food", name.to_string())
            }
        }
        _ => ("Other", regular_item_name(item_no).to_string()),
    }
}
