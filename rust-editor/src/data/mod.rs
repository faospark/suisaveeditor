use std::fmt;

/// Generic ID + Name option for `iced::widget::pick_list`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NamedOption {
    pub id: i64,
    pub name: &'static str,
}

impl fmt::Display for NamedOption {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.id == 0 {
            write!(f, "0 - None")
        } else {
            write!(f, "{} - {}", self.id, self.name)
        }
    }
}

pub const fn opt(id: i64, name: &'static str) -> NamedOption {
    NamedOption { id, name }
}

pub fn find_option(list: &[NamedOption], id: i64) -> NamedOption {
    list.iter()
        .copied()
        .find(|o| o.id == id)
        .unwrap_or(NamedOption { id, name: "Unknown" })
}

